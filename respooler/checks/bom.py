"""Generate docs/BOM.md and docs/print_guide.md from the parts' own metadata.
Run from respooler/:  ../.venv/Scripts/python.exe -m checks.bom
"""
import re
from collections import OrderedDict

import params as P
from assembly import collect
from lib.part import ROOT

# Vitamins whose notes don't name the part
VITAMIN_NAMES = {
    "gearbox_bearing_s1_": "623ZZ bearing 3x10x4",
    "gearbox_bearing_s2_": "625ZZ bearing 5x16x5",
    "gearbox_bearing_s3_rear": "625ZZ bearing 5x16x5",
    "gearbox_bearing_s3_front": "MR105ZZ bearing 5x10x4",
    "takeup_608_": "608ZZ bearing 8x22x7",
}
SKIP = ("ghost",)

# Hardware not modelled as parts (collected from workstream reports)
EXTRA = [
    ("M3 heat-set insert (M3 x 5, OD 4)", 58, "base box 8, gearbox 17, take-up 9, traverse 12, supply 8, wiper 4"),
    ("M4 heat-set insert", 1, "supply brake block"),
    ("M3 x 8 socket cap screw", 44, "38 x subsystem feet from under the base, 4 x e-box lid, 2 x motor cap"),
    ("M3 x 10..14 socket cap screw", 9, "gearbox posts/bracket/rear stop; trim to fit"),
    ("M3 x 25 socket cap screw + M3 nut", 4, "base half joint"),
    ("5 mm steel rod, 18 mm (dowel)", 4, "base half joint (cut from 5 mm rod)"),
    ("M2 x 10 thread-forming screw", 2, "microswitch"),
    ("22 AWG two-core wire", "1.5 m", "motor and auto-stop runs"),
    ("5 V or 6 V 2 A DC adapter, 5.5x2.1 barrel", 1, "never above 6 V"),
    ("Spare PTC fuses 0.5 / 1.1 A hold", "1 each", "for bench tuning of the stall trip"),
    ("Loctite 243 (medium threadlock)", "-", "take-up lock nuts 1-3"),
    ("Grease (PTFE or lithium)", "-", "shaft ends, gear bores"),
]


def vitamin_key(p):
    for prefix, name in VITAMIN_NAMES.items():
        if p.name.startswith(prefix):
            return name
    note = (p.notes or "").strip()
    return re.split(r"(?<=[a-z0-9)])[.;]\s(?=[A-Z])", note)[0] if note else p.name


def main():
    built = collect()
    printed, vit = [], OrderedDict()
    for sub, plist in built.items():
        for p in plist:
            if any(s in p.name for s in SKIP):
                continue
            if p.printed:
                bb = p.for_print().BoundingBox()
                printed.append((sub, p, (bb.xlen, bb.ylen, bb.zlen)))
            else:
                k = vitamin_key(p)
                e = vit.setdefault(k, dict(qty=0, subs=set()))
                e["qty"] += p.qty
                e["subs"].add(sub)

    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    b = ["# Bill of materials", "",
         "Generated by `python -m checks.bom` from the CAD model. Do not edit by hand; rerun it after design changes.", "",
         f"## Printed parts ({sum(p.qty for _, p, _ in printed)} pieces, PETG)", "",
         "| Subsystem | Part | Qty | Print size (mm) |", "|---|---|---|---|"]
    for sub, p, d in printed:
        b.append(f"| {sub} | `{p.name}` | {p.qty} | {d[0]:.0f} x {d[1]:.0f} x {d[2]:.0f} |")
    b += ["", "## Bought parts (modelled)", "", "| Item | Qty | Used in |", "|---|---|---|"]
    for k, e in vit.items():
        b.append(f"| {k} | {e['qty']} | {', '.join(sorted(e['subs']))} |")
    b += ["", "## Hardware and consumables (not modelled)", "", "| Item | Qty | Where |", "|---|---|---|"]
    for item, q, where in EXTRA:
        b.append(f"| {item} | {q} | {where} |")
    (docs / "BOM.md").write_text("\n".join(b) + "\n", encoding="utf-8")

    g = ["# Print guide", "",
         "Generated by `python -m checks.bom`. STL files are in `out/stl/` and are already in print orientation.", "",
         "## General settings (PETG)", "",
         "- Nozzle 0.4 mm, layer height 0.2 mm. Use 0.12–0.16 mm for the gears and the cam.",
         "- Gears, pinions, the cam and the bearing spacer: 100% infill, or at least 6 walls so the teeth are solid.",
         "- Structural parts (base halves, tower, gearbox frame, cradle): 4 walls, 30–40% gyroid infill.",
         "- Print a bearing-pocket test first and tune `PRESS_FIT` in `params.py` if the bearings are loose or too tight. Then re-export.",
         "- Heat-set inserts: M3 x 5 mm, OD 4 mm holes.",
         f"- Every part fits {P.BED_MAX[0]:.0f} x {P.BED_MAX[1]:.0f} x {P.BED_MAX[2]:.0f} mm.", "",
         "## Suggested order", "",
         "1. Gearbox first. Bench-test it on its own at 5–6 V before printing the rest; this is the riskiest part.",
         "2. Take-up tower and final gear, then check the mesh with the gearbox.",
         "3. Base halves (long prints), supply, wiper station, traverse.", "",
         "## Per-part notes", ""]
    cur = None
    for sub, p, d in printed:
        if sub != cur:
            g += ["", f"### {sub}", ""]
            cur = sub
        g.append(f"- **`{p.name}`** ({d[0]:.0f} x {d[1]:.0f} x {d[2]:.0f}): {p.notes or '-'}")
    (docs / "print_guide.md").write_text("\n".join(g) + "\n", encoding="utf-8")
    print(f"BOM: {len(printed)} printed parts, {len(vit)} vitamin lines -> {docs}")


if __name__ == "__main__":
    main()
